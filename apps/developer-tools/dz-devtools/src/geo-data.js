export function searchWilayas(query = '', lang = 'ar') {
  if (!query) return ALGERIA_WILAYAS;
  const q = query.trim().toLowerCase();
  return ALGERIA_WILAYAS.filter(w => {
    return w.code === q ||
      w.nameAr.toLowerCase().includes(q) ||
      w.nameFr.toLowerCase().includes(q) ||
      w.postalCode.startsWith(q) ||
      w.phoneCode === q ||
      w.communes.some(c => c.nameAr.toLowerCase().includes(q) || c.nameFr.toLowerCase().includes(q) || c.postalCode.startsWith(q));
  });
}
